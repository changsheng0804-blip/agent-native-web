def main():
    fails = []
    for sc, expect, txt in CASES:
        got = tq.SCENARIOS[sc]["judge"](txt)
        if got != expect:
            fails.append((sc, expect, got, txt))
    print(f"判分器回归: {len(CASES) - len(fails)}/{len(CASES)} 通过")
    for sc, expect, got, txt in fails:
        print(f"❌ [{sc}] 期望={expect} 实得={got}\n   输入={txt[:160]!r}")
    return 1 if fails else 0


if __name__ == "__main__":
    raise SystemExit(main())
